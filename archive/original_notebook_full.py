# =============================================================================
# CELL 52 — Bootstrap confidence interval on the effect size
# =============================================================================
# Mann-Whitney U is already the correct test for n=10; no test recovers a
# larger real sample. What we CAN do is stop reporting the effect size as a
# fixed point estimate and instead show how much it could plausibly move
# given only 10 named locations -- resampling the named locations (with
# replacement) is the part that matters here, since the background sample
# (n~4300) is large enough that its own resampling contributes comparatively
# little uncertainty.
#
# Caveat to state explicitly if you report this: a bootstrap built from only
# 10 original values is itself limited -- it characterizes uncertainty given
# your specific 10 points, but cannot conjure information those 10 points
# don't contain. Report it as "uncertainty in the estimate", not as
# equivalent to a larger validation sample.

def prob_superiority(a, b):
    u, _ = mannwhitneyu(a, b, alternative='greater')
    return u / (len(a) * len(b))

def bootstrap_effect_size_ci(named_vals, bg_vals, n_boot=10000, seed=42, ci=95):
    rng = np.random.default_rng(seed)
    n_named, n_bg = len(named_vals), len(bg_vals)
    boot_effects = np.empty(n_boot)
    for i in range(n_boot):
        named_sample = rng.choice(named_vals, size=n_named, replace=True)
        bg_sample = rng.choice(bg_vals, size=n_bg, replace=True)
        boot_effects[i] = prob_superiority(named_sample, bg_sample)
    lower = np.percentile(boot_effects, (100 - ci) / 2)
    upper = np.percentile(boot_effects, 100 - (100 - ci) / 2)
    point = prob_superiority(named_vals, bg_vals)
    return point, lower, upper, boot_effects

