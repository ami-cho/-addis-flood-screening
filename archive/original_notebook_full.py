# For each road segment, sample flow accumulation at its midpoint
def get_accumulation_at_point(row, acc, grid):
    midpoint = row.geometry.interpolate(0.5, normalized=True)
    col, r = ~grid.affine * (midpoint.x, midpoint.y)
    col, r = int(col), int(r)
    if 0 <= r < acc.shape[0] and 0 <= col < acc.shape[1]:
        return acc[r, col]
    return np.nan

