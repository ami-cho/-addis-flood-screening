from pysheds.grid import Grid

grid = Grid.from_raster('addis_fabdem.tif')
dem = grid.read_raster('addis_fabdem.tif')

# Real terrain has "pits" (single low pixels) and "depressions" (bigger sinks)
# that would trap water unrealistically — these three steps fix that so
# water can flow all the way through the DEM
pit_filled_dem = grid.fill_pits(dem)
flooded_dem = grid.fill_depressions(pit_filled_dem)
inflated_dem = grid.resolve_flats(flooded_dem)

# For every pixel, figure out which direction water flows (D8 = 8 possible directions)
fdir = grid.flowdir(inflated_dem)

# Now count: for every pixel, how many upstream pixels drain into it
acc = grid.accumulation(fdir)

print("Flow accumulation computed. Max accumulation:", acc.max())

