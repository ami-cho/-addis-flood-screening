# CELL 26 — Design storm runoff depth (SCS-CN formula), placeholder P
# =============================================================================
P = 50  # mm, placeholder -- Cell 28/29 will replace this with a real value

def cn_to_runoff(cn_val, p=P):
    if cn_val <= 0:
        return 0
    s = (25400 / cn_val) - 254
    if p <= 0.2 * s:
        return 0.0
    return ((p - 0.2 * s) ** 2) / (p + 0.8 * s)

